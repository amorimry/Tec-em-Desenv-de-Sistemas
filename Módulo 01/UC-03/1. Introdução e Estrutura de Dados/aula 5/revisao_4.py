#Revisão 4: Crie um programa que pede os 3 lados de um triângulo e calcule o seu perímetro.
print ("Calcúle o perímetro de um triângilo.")
lado1 = float(input("Insira o primeiro lado: "))
lado2 = float(input("Insira o segundo lado: "))
lado3 = float(input("Insira o terceiro lado: "))

perimetro = lado1+lado2+lado3

print (f"O valor do perímetro é: {perimetro}")